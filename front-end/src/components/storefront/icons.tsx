export function Arrow({
  className = "h-4 w-4",
  left = false,
  flipRtl = true,
}: {
  className?: string;
  left?: boolean;
  flipRtl?: boolean;
}) {
  const dirClass = flipRtl
    ? left
      ? "rotate-180 rtl:rotate-0"
      : "rtl:rotate-180"
    : left
      ? "rotate-180"
      : "";

  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={`${className} ${dirClass}`}
    >
      <path d="M5 12h14" />
      <path d="m12 5 7 7-7 7" />
    </svg>
  );
}

